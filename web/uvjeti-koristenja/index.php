<h1>Uvjeti korištenja Fakturive</h1>
<p><strong>Nacrt od 9. studenoga 2026.</strong> Prije stupanja na snagu
potrebno je upisati potpuni registrirani naziv pružatelja, adresu,
službeni kontakt, nadležnost, pravila naplate i potvrditi tekst s
pravnim savjetnikom. Ne postoji odobrenje regulatora temeljeno
isključivo na tekstu ovih uvjeta.</p>
<h2>1. Predmet</h2>
<p>Fakturiva je digitalni sustav za izradu poslovnih dokumenata, računa
i ponuda, evidenciju naplate, pregled izvještaja, upravljanje
klijentima i odabranim poreznim obračunima. Sustav obuhvaća
Android aplikaciju i web račun te, kada je objavljen,
Windows klijent. Dostupnost funkcija ovisi o verziji, državi,
pravilima, tehničkoj podršci i korisničkim postavkama.</p>
<h2>2. Korisnici i registracija</h2>
<p>Usluga je namijenjena osobama koje posluju u vlastito ime ili
u ime ovlaštene organizacije. Registracijom korisnik jamči da
ima pravo otvoriti račun i obrađivati unesene podatke.
Korisnički račun je osoban ili organizacijski, a pristup
mora biti ograničen na ovlaštene osobe. Korisnik mora štititi
vjerodajnice, koristiti jaku lozinku za sigurnosne kopije
i odmah prijaviti sumnju na zlouporabu.</p>
<h2>3. Odnos korisničkog PIN-a i poslužiteljskog identiteta</h2>
<p>PIN za web prijavu služi autentifikaciji korisnika. Zasebna
snažna lozinka štiti poslužiteljski pristup i šifrirane
poslovne podatke. Lokalna radna kopija na Androidu
ne smije se zamijeniti za potvrđenu kopiju na serveru.
Za oporavak nakon deinstalacije ili promjene uređaja nužno je
da je na serveru potvrđeno spremljena kopija i da korisnik
ima odgovarajuće vjerodajnice. Pružatelj ne može jamčiti
apsolutnu zaštitu od svake tehničke okolnosti ni vratiti
kopiju za koju korisnik nije dovršio prijenos ili je
izbrisana prema valjanom zahtjevu.</p>
<h2>4. Planovi i dostupnost</h2>
<p>Sustav može dodjeljivati oznake tarifnih razina FREE, PRO i
BUSINESS. Funkcije i eventualne cijene plaćenih planova moraju
biti transparentno objavljene prije ugovaranja, zajedno s
uvjetima obnove, otkaza, prava na povrat i porezima.
Sama oznaka tarife ne predstavlja potvrdu naplate.
Pretplate i načini plaćanja neće biti uključeni bez
posebno provjerenog zakonskog i platformskog postupka.
Aplikacija ne prikazuje ponude plaćenih planova ako
takva prodaja nije aktivirana.</p>
<h2>5. Obveze korisnika</h2>
<p>Korisnik je odgovoran za točnost izdavatelja, poreznog
identifikatora, valute, statusa PDV-a, podataka o računu,
načinu naplate, poslovnom prostoru i operateru, ako su
potrebni za konkretan pravni režim. Mora provjeriti
ispravnost KPR-a, PO-SD-a i drugih izvještaja s
bankovnim izvodima, blagajnom i stvarnim poslovnim događajima
te po potrebi pribaviti profesionalni računovodstveni savjet.
Nije dopušteno unositi nezakonit ili tuđ sadržaj bez pravne osnove.</p>
<h2>6. Računi, elektronički računi i fiskalizacija</h2>
<p>PDF je vizualni prikaz dokumenta i sam po sebi nije potvrda
fiskalizacije niti strukturirani eRačun. Fiskalizacija 1.0,
Fiskalizacija 2.0 i elektronička razmjena mogu zahtijevati
posebne certifikate, identifikatore, servise i zakonski
definirane podatke. Nijedan račun ne smije se označavati
fiskaliziranim bez uspješnog odgovora nadležne službe.
Korisnik može koristiti osnovne funkcije gdje je to
zakonski dopušteno; software ne oslobađa zakonske obveze
izdavanja strukturiranih računa i fiskalizacije kada su
one za korisnika obvezne.</p>
<h2>7. Prilagodba obrazaca i međunarodno poslovanje</h2>
<p>Odabir boje, predloška ili logotipa mijenja samo
vizualni prikaz. Obvezna polja računa ne smiju se ukloniti.
Različiti pravni oblici (obrt, d.o.o., Ltd, Inc, GmbH i drugi)
podliježu različitim pravilima o dokumentiranju,
porezu i registraciji. Fakturiva smije omogućiti
samo one službene obrasce za koje su važeća pravila,
sheme i izračuni potvrđeni. Obrazac za drugu državu
ne smije se prikazivati kao porezno usklađen na
temelju sličnosti s hrvatskim obrascem.</p>
<h2>8. Pohrana, integritet i dostupnost</h2>
<p>Sustav koristi poslužiteljske korisničke zapise,
odvojene šifrirane sigurnosne kopije i kontrolu revizija.
Privremeni lokalni podatci mogu postojati radi rada
bez mreže. Poslužitelj i ključ za šifriranje moraju se
redovito sigurnosno kopirati izvan istoga hostinga,
a povrat redovito testirati. U slučaju prekida veze
nepotvrđene promjene moraju biti jasno označene.
Iako se poduzimaju razumne tehničke i organizacijske
mjere zaštite, apsolutno jamstvo neprekidnosti
ili gubitka nula podataka nije tehnički moguće.</p>
<h2>9. Zaštita osobnih podataka</h2>
<p>Pravila obrade, prava ispitanika, sigurnost i kontakt
navedeni su u <a href="../politika-privatnosti/">Politici privatnosti</a>.
Poslovni korisnik odgovoran je za zakonitost obrade
podataka svojih klijenata. Ako pružatelj obrađuje
osobne podatke u njegovo ime, treba zaključiti
ugovor o obradi prema članku 28. GDPR-a.</p>
<h2>10. Sigurnost i zabranjene uporabe</h2>
<p>Korisnik ne smije pokušavati pristupiti drugim računima,
zaobilaziti ograničenja, slati zlonamjeran kod niti
koristiti sustav za prijevaru, neovlaštenu obradu ili
prijenos tuđih osobnih podataka. Kod ozbiljne
sigurnosne prijetnje pristup se može privremeno
ograničiti uz razmjeran postupak. Ograničenje nije
zamjena za brisanje korisničkih podataka.</p>
<h2>11. Brisanje i arhiviranje</h2>
<p>Račun se može zatražiti za brisanje iz aplikacije
ili preko <a href="../delete-account.php">javne stranice za brisanje</a>.
S korisničkim računom brišu se pridruženi podatci
koji ne podliježu zakonitom zadržavanju. Poslovni korisnik
prije brisanja mora organizirati čuvanje dokumentacije
za zakonom propisane rokove. Vremena brisanja rezervnih
kopija ovise o stvarnoj politici pohrane i moraju se
jasno odrediti prije produkcije.</p>
<h2>12. Intelektualno vlasništvo</h2>
<p>Ime, logotip, kod i dizajn Fakturive imaju pripadajuće
nositelje prava i primjenjive licence. Korisnik zadržava
prava na vlastite poslovne podatke, vlastite logotipe i
dokumente, uz licence potrebne da ih sustav obradi i
prikaže. Dokumenti i licencirane sastavnice trećih strana
zadržavaju prava njihovih nositelja.</p>
<h2>13. Podrška, izmjene i prigovori</h2>
<p>Podrška: <a href="mailto:info@fakturiva.com">info@fakturiva.com</a>.
O značajnim promjenama funkcionalnosti i uvjeta
