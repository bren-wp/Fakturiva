primjenjuju se obvezna prava potrošača koja nije
dopušteno isključiti ovim uvjetima. Uvjeti o
odgovornosti i nadležnosti moraju se pregledati za
ciljane države i korisničke skupine.</p>
<h2>14. Mjerodavno pravo i sporovi</h2>
<p>Predviđena primjena hrvatskog prava ne smije
